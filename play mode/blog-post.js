// ===== LOAD BLOG POST =====
function loadBlogPost() {
    const container = document.getElementById('blogPostContainer');
    if (!container) return;

    // Get post ID from URL
    const urlParams = new URLSearchParams(window.location.search);
    const postId = urlParams.get('id');

    if (!postId) {
        container.innerHTML = `
            <div class="blog-post-error">
                <h2>Article not found</h2>
                <p>The blog post you're looking for doesn't exist.</p>
                <a href="blog.html" class="btn-red">Back to Blog</a>
            </div>
        `;
        return;
    }

    // Find the post
    const post = blogPosts.find(p => p.id === postId);

    if (!post) {
        container.innerHTML = `
            <div class="blog-post-error">
                <h2>Article not found</h2>
                <p>Sorry, we couldn't find the article you're looking for.</p>
                <a href="blog.html" class="btn-red">Back to Blog</a>
            </div>
        `;
        return;
    }

    // Render the post
    container.innerHTML = `
        <div class="blog-post">
            <a href="blog.html" class="blog-back">
                <svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><line x1="19" y1="12" x2="5" y2="12"/><polyline points="12 19 5 12 12 5"/></svg>
                Back to Blog
            </a>

            <div class="blog-post-header">
                <span class="blog-category-header">${post.category}</span>
                <h1 class="blog-post-title">${post.title}</h1>
                <div class="blog-post-meta">
                    <span><i class="fa-regular fa-calendar"></i> ${post.date}</span>
                    <span><i class="fa-regular fa-clock"></i> ${post.readTime}</span>
                    <span><i class="fa-regular fa-user"></i> ${post.author}</span>
                </div>
            </div>

            <div class="blog-post-image">
                <img src="${post.image}" alt="${post.title}" loading="lazy">
            </div>

            <div class="blog-post-body">
                ${post.content}
            </div>

            <div class="blog-post-footer">
                <div class="blog-share">
                    <span>Share this article:</span>
                    <button onclick="shareArticle('facebook', '${post.title}', '${window.location.href}')" class="share-btn">
                        <i class="fa-brands fa-facebook"></i>
                    </button>
                    <button onclick="shareArticle('twitter', '${post.title}', '${window.location.href}')" class="share-btn">
                        <i class="fa-brands fa-twitter"></i>
                    </button>
                    <button onclick="shareArticle('linkedin', '${post.title}', '${window.location.href}')" class="share-btn">
                        <i class="fa-brands fa-linkedin"></i>
                    </button>
                    <button onclick="copyLink('${window.location.href}')" class="share-btn copy-btn">
                        <i class="fa-regular fa-copy"></i>
                    </button>
                </div>
            </div>
        </div>
    `;

    // Re-initialize Lucide icons
    if (typeof lucide !== 'undefined') {
        lucide.createIcons();
    }
}

// ===== SHARE FUNCTIONS =====
function shareArticle(platform, title, url) {
    let shareUrl = '';
    switch(platform) {
        case 'facebook':
            shareUrl = `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`;
            break;
        case 'twitter':
            shareUrl = `https://twitter.com/intent/tweet?text=${encodeURIComponent(title)}&url=${encodeURIComponent(url)}`;
            break;
        case 'linkedin':
            shareUrl = `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`;
            break;
    }
    if (shareUrl) {
        window.open(shareUrl, '_blank', 'width=600,height=400');
    }
}

function copyLink(url) {
    navigator.clipboard.writeText(url).then(() => {
        const btn = document.querySelector('.copy-btn');
        if (btn) {
            btn.classList.add('copied');
            btn.innerHTML = '<i class="fa-regular fa-check"></i> Copied!';
            setTimeout(() => {
                btn.classList.remove('copied');
                btn.innerHTML = '<i class="fa-regular fa-copy"></i>';
            }, 3000);
        }
    });
}

// ===== NAV =====
document.addEventListener('DOMContentLoaded', function() {
    const hamburger = document.getElementById('hamburger');
    const navLinks = document.getElementById('navLinks');

    if (hamburger && navLinks) {
        hamburger.addEventListener('click', function() {
            navLinks.classList.toggle('open');
            this.classList.toggle('active');
        });

        navLinks.querySelectorAll('a').forEach(l => l.addEventListener('click', () => {
            navLinks.classList.remove('open');
            hamburger.classList.remove('active');
        }));
    }

    window.addEventListener('resize', () => {
        if (window.innerWidth > 768 && navLinks) {
            navLinks.classList.remove('open');
            if (hamburger) hamburger.classList.remove('active');
        }
    });

    // Load blog post
    loadBlogPost();
});